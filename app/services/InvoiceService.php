<?php

declare(strict_types=1);

final class InvoiceService
{
    /**
     * --------------------------------------------------------------------------
     * پیدا کردن فاکتور
     * --------------------------------------------------------------------------
     */
    public static function find(
        PDO $db,
        int $invoiceId
    ): ?array {

        $stmt = $db->prepare("
            SELECT
                i.id,
                i.invoice_number,
                i.order_id,
                i.user_id,
                i.total AS invoice_total,

                o.order_number,
                o.status,
                o.subtotal,
                o.discount_total,
                o.shipping_fee,
                o.shipping_cost,

                o.shipping_name,
                o.shipping_mobile,
                o.shipping_province,
                o.shipping_city,
                o.shipping_address,
                o.shipping_postal,

                o.created_at AS order_created_at

            FROM invoices i

            INNER JOIN orders o
                ON o.id = i.order_id

            WHERE i.id = ?

            LIMIT 1
        ");

        $stmt->execute([
            $invoiceId
        ]);

        $invoice =
            $stmt->fetch(PDO::FETCH_ASSOC);

        if (!$invoice) {
            return null;
        }

        /*
        |--------------------------------------------------------------------------
        | اقلام فاکتور
        |--------------------------------------------------------------------------
        */

        $invoice['items'] =
            self::getItems(
                $db,
                (int)$invoice['order_id']
            );

        /*
        |--------------------------------------------------------------------------
        | محاسبه جمع‌ها
        |--------------------------------------------------------------------------
        */

        $invoice['totals'] =
            self::calculateTotals(
                $invoice,
                $invoice['items']
            );

        return $invoice;
    }


    /**
     * --------------------------------------------------------------------------
     * اقلام سفارش
     * --------------------------------------------------------------------------
     */
    private static function getItems(
        PDO $db,
        int $orderId
    ): array {

        $stmt = $db->prepare("
            SELECT
                oi.id,
                oi.order_id,
                oi.product_id,
                oi.product_code,
                oi.product_name,
                oi.qty,

                oi.base_unit_price,
                oi.discount_percent,
                oi.discount_amount,

                oi.unit_price,
                oi.line_total

            FROM order_items oi

            WHERE oi.order_id = ?

            ORDER BY oi.id ASC
        ");

        $stmt->execute([
            $orderId
        ]);

        return $stmt->fetchAll(
            PDO::FETCH_ASSOC
        );
    }


    /**
     * --------------------------------------------------------------------------
     * محاسبه جمع‌های فاکتور
     * --------------------------------------------------------------------------
     *
     * subtotal:
     * مبلغ کالاها قبل از تخفیف
     *
     * discount:
     * مجموع تخفیف کالاها
     *
     * after_discount:
     * مبلغ کالاها بعد از تخفیف
     *
     * shipping:
     * هزینه ارسال
     *
     * total:
     * مبلغ نهایی سفارش
     * --------------------------------------------------------------------------
     */
    private static function calculateTotals(
        array $invoice,
        array $items
    ): array {

        /*
        |--------------------------------------------------------------------------
        | جمع قبل از تخفیف
        |--------------------------------------------------------------------------
        */

        $itemsSubtotal = 0;


        /*
        |--------------------------------------------------------------------------
        | مجموع تخفیف
        |--------------------------------------------------------------------------
        */

        $itemsDiscount = 0;


        /*
        |--------------------------------------------------------------------------
        | جمع نهایی اقلام
        |--------------------------------------------------------------------------
        */

        $itemsTotal = 0;


        foreach ($items as $item) {

            $qty =
                (int)($item['qty'] ?? 0);

            $baseUnitPrice =
                (int)(
                    $item['base_unit_price']
                    ?? 0
                );

            $discountAmount =
                (int)(
                    $item['discount_amount']
                    ?? 0
                );

            $lineTotal =
                (int)(
                    $item['line_total']
                    ?? 0
                );


            /*
             * برای سفارش‌های جدید:
             * base_unit_price در دیتابیس ذخیره شده است.
             */

            if (
                $baseUnitPrice > 0
                && $qty > 0
            ) {

                $itemsSubtotal +=
                    $baseUnitPrice * $qty;
            } else {

                /*
                 * سازگاری با سفارش‌های قدیمی
                 * که قبل از اضافه شدن ستون جدید ثبت شده‌اند.
                 */

                $itemsSubtotal +=
                    $lineTotal
                    + $discountAmount;
            }


            $itemsDiscount +=
                $discountAmount;


            $itemsTotal +=
                $lineTotal;
        }


        /*
        |--------------------------------------------------------------------------
        | تخفیف ثبت‌شده در orders
        |--------------------------------------------------------------------------
        */

        $orderDiscount =
            (int)(
                $invoice['discount_total']
                ?? 0
            );


        /*
        |--------------------------------------------------------------------------
        | اگر discount_total سفارش موجود باشد،
        | آن را ملاک قرار می‌دهیم.
        |
        | در غیر این صورت از order_items استفاده می‌کنیم.
        |--------------------------------------------------------------------------
        */

        $discount =
            $orderDiscount > 0
            ? $orderDiscount
            : $itemsDiscount;


        /*
        |--------------------------------------------------------------------------
        | subtotal ثبت‌شده سفارش
        |--------------------------------------------------------------------------
        */

        $orderSubtotal =
            (int)(
                $invoice['subtotal']
                ?? 0
            );


        /*
        |--------------------------------------------------------------------------
        | اگر subtotal سفارش معتبر باشد،
        | همان را استفاده می‌کنیم.
        |--------------------------------------------------------------------------
        */

        $subtotal =
            $orderSubtotal > 0
            ? $orderSubtotal
            : $itemsSubtotal;


        /*
        |--------------------------------------------------------------------------
        | مبلغ کالاها بعد از تخفیف
        |--------------------------------------------------------------------------
        */

        $afterDiscount =
            max(
                0,
                $subtotal - $discount
            );


        /*
        |--------------------------------------------------------------------------
        | هزینه ارسال
        |--------------------------------------------------------------------------
        */

        $shipping =
            (int)(
                $invoice['shipping_fee']
                ?? 0
            );


        /*
        |--------------------------------------------------------------------------
        | مبلغ نهایی
        |--------------------------------------------------------------------------
        */

        $invoiceTotal =
            (int)(
                $invoice['invoice_total']
                ?? 0
            );


        /*
        |--------------------------------------------------------------------------
        | اگر total در invoices موجود باشد،
        | همان مبلغ تاریخی فاکتور ملاک است.
        |
        | در غیر این صورت:
        |
        | کالا بعد از تخفیف + ارسال
        |--------------------------------------------------------------------------
        */

        $total =
            $invoiceTotal > 0
            ? $invoiceTotal
            : (
                $afterDiscount
                + $shipping
            );


        /*
        |--------------------------------------------------------------------------
        | مبلغ پرداخت‌شده
        |--------------------------------------------------------------------------
        */

        $paidTotal = 0;

        /*
         * فعلاً سیستم پرداخت تاریخی شما از این سرویس
         * مبلغ paid را تأمین نمی‌کند.
         *
         * بنابراین صفر نگه داشته می‌شود.
         *
         * در مرحله پرداخت می‌توانیم این قسمت را
         * به payments متصل کنیم.
         */

        $paid =
            max(
                0,
                $paidTotal
            );


        /*
        |--------------------------------------------------------------------------
        | مانده
        |--------------------------------------------------------------------------
        */

        $remaining =
            max(
                0,
                $total - $paid
            );


        /*
        |--------------------------------------------------------------------------
        | مالیات
        |--------------------------------------------------------------------------
        |
        | در ساختار فعلی سفارش مالیات نداریم.
        | بنابراین عدد جعلی تولید نمی‌کنیم.
        |--------------------------------------------------------------------------
        */

        $tax = 0;


        return [

            /*
             * جمع کالاها قبل از تخفیف
             */
            'subtotal' =>
            $subtotal,

            /*
             * مجموع تخفیف
             */
            'discount' =>
            $discount,

            /*
             * جمع کالاها بعد از تخفیف
             */
            'after_discount' =>
            $afterDiscount,

            /*
             * هزینه ارسال
             */
            'shipping' =>
            $shipping,

            /*
             * مالیات
             */
            'tax' =>
            $tax,

            /*
             * مبلغ نهایی
             */
            'total' =>
            $total,

            /*
             * پرداخت‌شده
             */
            'paid' =>
            $paid,

            /*
             * مانده
             */
            'remaining' =>
            $remaining,
        ];
    }


    /**
     * --------------------------------------------------------------------------
     * فرمت مبلغ
     * --------------------------------------------------------------------------
     */
    public static function money(
        int|float $amount
    ): string {

        return number_format(
            (float)$amount
        ) . ' تومان';
    }


    /**
     * --------------------------------------------------------------------------
     * تبدیل ارقام انگلیسی به فارسی
     * --------------------------------------------------------------------------
     */
    public static function faDigits(
        string $value
    ): string {

        return strtr(
            $value,
            [
                '0' => '۰',
                '1' => '۱',
                '2' => '۲',
                '3' => '۳',
                '4' => '۴',
                '5' => '۵',
                '6' => '۶',
                '7' => '۷',
                '8' => '۸',
                '9' => '۹',
            ]
        );
    }
}
